import type { RouteBounds, RoutePoint } from "@/types/trail";

type CompactPoint = readonly [lat: number, lng: number, ele: number, distKm: number];

export interface SeedRouteGeometry {
  points: RoutePoint[];
  distanceKm: number;
  elevationGainM: number;
  startLat: number;
  startLng: number;
  endLat: number;
  endLng: number;
  bounds: RouteBounds;
}

function buildGeometry(
  compact: readonly CompactPoint[],
  distanceKm: number,
  elevationGainM: number,
  bounds: RouteBounds,
): SeedRouteGeometry {
  const points: RoutePoint[] = compact.map(([lat, lng, ele, distKm]) => ({
    lat,
    lng,
    ele,
    distKm,
  }));
  const first = points[0];
  const last = points[points.length - 1];
  return {
    points,
    distanceKm,
    elevationGainM,
    startLat: first.lat,
    startLng: first.lng,
    endLat: last.lat,
    endLng: last.lng,
    bounds,
  };
}

